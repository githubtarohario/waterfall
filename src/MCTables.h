#pragma once
// =====================================================================
//  MCTables.h
//  マーチングキューブ法の三角形テーブルを「起動時に生成」する。
//
//  256 通りの頂点内外パターンごとに、交差エッジを面の周りで辿って
//  閉ループを作り、扇状に三角形分割する。曖昧な面 (対角の 2 頂点だけが内側)
//  は「内側頂点同士を分離する」規則で一貫して処理するため、隣接セル間で
//  面の分割が必ず一致し、穴の無い多様体メッシュが得られる。
//
//  頂点番号 : ビット表現  v = (x, y, z) = (bit0, bit1, bit2)
//  エッジ番号: 0-3 = x 方向, 4-7 = y 方向, 8-11 = z 方向 (MC_EDGE_VERTS 参照)
//  ※ HLSL 側 (mc_cubes.hlsl) の定数配列と完全に一致させること。
// =====================================================================
#include <cstdint>
#include <vector>

namespace mc
{
    constexpr int NUM_CASES   = 256;   // 内外パターン数
    constexpr int TABLE_STRIDE = 32;   // 1 パターンあたりのエッジ番号数 (3*三角形数 + 終端 -1)

    // 12 本のエッジの両端頂点番号
    constexpr int EDGE_VERTS[12][2] = {
        {0,1},{2,3},{4,5},{6,7},   // x 方向
        {0,2},{1,3},{4,6},{5,7},   // y 方向
        {0,4},{1,5},{2,6},{3,7},   // z 方向
    };

    // 三角形テーブルを生成する。戻り値のサイズは NUM_CASES * TABLE_STRIDE。
    // 各パターンの先頭から 3 個ずつエッジ番号が並び、-1 で終端。
    std::vector<int32_t> GenerateTriangleTable();

    // 生成したテーブルの自己検証。球のスカラー場を CPU で MC し、
    // 「全エッジが向きの異なる 2 つの三角形に共有されている (閉じた多様体)」
    // と「三角形の向きが外向き (勾配の逆)」を確認する。true なら合格。
    bool SelfTest(const std::vector<int32_t>& table, int32_t* outTriangleCount = nullptr);
}
